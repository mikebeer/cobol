const REPO = __dirname + '/../';
const COBOL = REPO + 'cobol';
const FILE = (f) => fs.readFileSync(REPO + f, 'utf8').replace(/\n+$/, '').split('\n');
const sh = (cmd, input) => execSync(cmd, { input: input || '', shell: '/bin/bash', stdio: ['pipe', 'pipe', 'pipe'] }).toString();
const lines = (s) => s.replace(/\n+$/, '').split('\n');

// Run a shell command in directory d; returns {out, rc}. The command sees a
// function cobol that runs the translator under test.
const SHELL = (d, cmd, input) => {
  const script = 'cobol() { ' + COBOL + ' "$@"; }; cd ' + d + '; ' + cmd + ' 2>&1';
  try { return { out: sh(script, input), rc: 0 }; } catch (e) {
    return { out: (e.stdout || '').toString(), rc: e.status };
  }
};

// Translate, build and run COBOL sources.
//   files: {name: text} written into a fresh directory
//   o.build:  the translator arguments (default '-c s.cob -o s')
//   o.input:  standard input of the program
//   o.run:    the command that runs the program (default './s')
//   o.rc:     the return code the program is expected to give (default 0)
//   o.after:  more commands whose output is shown (cat of a file, od ...)
//   o.fail:   the translation is expected to fail (a diagnostic example)
const RUNSRC = (files, o = {}) => {
  const d = fs.mkdtempSync('/tmp/cobrun-');
  try {
    for (const k of Object.keys(files)) fs.writeFileSync(d + '/' + k, files[k]);
    for (const k of Object.keys(o.extra || {})) fs.writeFileSync(d + '/' + k, o.extra[k]);
    for (const c of o.pre || []) {
      const p = SHELL(d, c);
      if (p.rc !== 0) throw new Error('command failed: ' + c + '\n' + p.out);
    }
    const b = SHELL(d, 'cobol ' + (o.build || '-c s.cob -o s'));
    if (o.fail) return { out: lines(b.out), rc: b.rc };
    if (b.rc !== 0) throw new Error('translation failed:\n' + b.out);
    let out = [];
    if (o.run !== null) {
      const r = SHELL(d, "timeout 10 sh -c '" + (o.run || './s').replace(/'/g, "'\\''") + "'", o.input);
      const want = o.rc === undefined ? 0 : o.rc;
      if (r.rc !== want) throw new Error('run gave return code ' + r.rc + ' (wanted ' + want + '):\n' + r.out);
      out = lines(r.out);
    }
    for (const c of o.after || []) {
      out.push('$ ' + c);
      out.push(...lines(SHELL(d, c).out));
    }
    return { out: out.slice(0, o.max || 70), rc: 0 };
  } finally { sh('rm -rf ' + d); }
};

// Source text: lines are given relative to column 8; fixed format adds the
// 7 columns of the sequence and indicator areas and checks the 72 column limit.
const FIXED = (ls) => ls.map((l) => {
  if (l[0] === '|') return l.slice(1);
  const t = l === '' ? '' : '       ' + l;
  if (t.length > 72 && !/^ {6}[*\/]/.test(t)) throw new Error('line longer than 72 columns: ' + t);
  return t;
});
const PARA = /^[A-Z0-9][A-Z0-9-]*( SECTION)?\.$/;
const PROGRAM = (o) => {
  const L = ['IDENTIFICATION DIVISION.', 'PROGRAM-ID. ' + (o.id || 'DEMO') + '.'];
  if (o.env) L.push('ENVIRONMENT DIVISION.', ...o.env);
  if (o.fd || o.ws || o.ls) L.push('DATA DIVISION.');
  if (o.fd) L.push('FILE SECTION.', ...o.fd);
  if (o.ws) L.push('WORKING-STORAGE SECTION.', ...o.ws);
  if (o.ls) L.push('LINKAGE SECTION.', ...o.ls);
  L.push('PROCEDURE DIVISION.');
  // Without paragraph names every line is relative to column 12; with
  // them, lines that start with a blank are already at their column.
  const isPara = (l) => PARA.test(l) && !/^END-/.test(l);
  const hasPara = o.proc.some(isPara);
  for (const l of o.proc) {
    if (l[0] === '|' || isPara(l)) L.push(l);
    else L.push(hasPara && l[0] === ' ' ? l : '    ' + l);
  }
  return L;
};
// DEMO(caption, {id, env, fd, ws, ls, proc | src, input, build, after, free, rc}):
// a complete program, followed by what it prints.
const DEMO = (cap, o, fig) => {
  const body = o.src || PROGRAM(o);
  const text = o.free ? body : FIXED(body);
  const build = o.build || (o.free ? '-free -c s.cob -o s' : '-c s.cob -o s');
  const extra = {};
  const pre = [];
  for (const k of Object.keys(o.copy || {})) {
    extra[k] = FIXED(o.copy[k]).join('\n') + '\n';
    pre.push('      * ' + k, ...FIXED(o.copy[k]), '');
  }
  const r = RUNSRC({ 's.cob': text.join('\n') + '\n' }, { ...o, build, extra });
  r.out = r.out.map((l) => l.replace(/s\.cob/g, 'demo.cob'));
  const shown = build.replace('s.cob', 'demo.cob').replace('-o s', '-o demo');
  const cmds = [];
  if (o.free || o.build || o.fail) cmds.push('$ cobol ' + shown);
  if (!o.fail) cmds.push(o.run === undefined ? '$ ./demo' : '$ ' + o.run.replace('./s', './demo'));
  if (pre.length) pre.push('      * demo.cob');
  const ruler = o.ruler ? ['         1         2         3         4         5         6         7', '123456789012345678901234567890123456789012345678901234567890123456789012'] : [];
  return CODE(fig, cap, pre.concat(ruler, text, ['', ...cmds]).concat(r.out));
};
// A file of the repository, run as a program.
const EX = (cap, f, o = {}, fig) => {
  const text = FILE(f);
  const name = f.split('/').pop();
  const extra = {};
  for (const e of o.data || []) extra[e.split('/').pop()] = fs.readFileSync(REPO + e, 'utf8');
  const r = RUNSRC({ [name]: text.join('\n') + '\n' }, { extra, build: '-c ' + name + ' -o s', ...o });
  const lns = text.concat(['', '$ ./' + name.replace(/\.cob$/, '')]).concat(r.out);
  return CODE(fig, cap, lns);
};
// Several repository files built together. cmds are the translator
// commands (FILES stands for the file names); the last one builds the program.
const EXM = (cap, files, cmds, o = {}, fig) => {
  const all = {};
  files.forEach((f) => { all[f.split('/').pop()] = fs.readFileSync(REPO + f, 'utf8'); });
  const names = files.map((f) => f.split('/').pop()).join(' ');
  const cs = cmds.map((c) => c.replace('FILES', names));
  const r = RUNSRC(all, { run: './prog', ...o, pre: cs.slice(0, -1).map((c) => 'cobol ' + c), build: cs[cs.length - 1] });
  const L = [];
  files.forEach((f) => {
    const n = f.split('/').pop();
    L.push(/\.c$/.test(n) ? '/* ' + n + ' */' : '      * ' + n, ...FILE(f), '');
  });
  const shown = cs.map((c) => '$ cobol ' + c);
  return CODE(fig, cap, L.concat(shown, ['$ ' + (o.runshown || './prog')], r.out));
};
// A session at the shell prompt.
const SESSION = (cap, cmds, o = {}, fig) => {
  const d = fs.mkdtempSync('/tmp/cobrun-');
  const out = [];
  try {
    for (const k of Object.keys(o.files || {})) fs.writeFileSync(d + '/' + k, o.files[k]);
    for (const c of cmds) {
      const [shown, real] = Array.isArray(c) ? c : [c, c];
      out.push('$ ' + shown);
      const r = SHELL(d, real);
      if (r.out) out.push(...lines(r.out));
    }
  } finally { sh('rm -rf ' + d); }
  return CODE(fig, cap, out);
};

