const WORDS = (file, name) => {
  const t = fs.readFileSync(REPO + 'src/' + file, 'utf8');
  const m = new RegExp(name + '\\[\\] = \\{([^}]*)\\}').exec(t);
  if (!m) throw new Error('array not found: ' + name);
  return (m[1].match(/"[^"]+"/g) || []).map((w) => w.slice(1, -1));
};
const COLS = (words, n) => {
  const w = Array.from(new Set(words)).sort();
  const rows = [];
  const per = Math.ceil(w.length / n);
  for (let i = 0; i < per; i++) {
    const r = [];
    for (let j = 0; j < n; j++) r.push(w[i + j * per] ? '`' + w[i + j * per] + '`' : '');
    rows.push(r);
  }
  return rows;
};
