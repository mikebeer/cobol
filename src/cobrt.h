    r->a.type = CT_ALNUM;
    r->a.digits = 0;
    r->a.scale = 0;
    r->a.flags = 0;
    r->a.pic = 0;
    r->f.size = n;
    r->f.data = r->buf;
    r->f.attr = &r->a;
